-- Links every auth user to a company
create table if not exists public.profiles (
    id         uuid   not null,
    company_id bigint null,
    full_name   text   null,
    avatar_url  text   null,
    created_at timestamp with time zone not null default now(),
    writed_at timestamp with time zone null,
    constraint profiles_pkey primary key (id),
    constraint profiles_id_fkey foreign key (id) references auth.users (id) on delete cascade,
    constraint profiles_company_id_fkey foreign key (company_id) references public.company (id) on delete set null
);


-- Create user_role reference / lookup table
create table public.roles (
    id          bigint generated by default as identity not null,
    name        text   not null,
    description text   null,
    created_at timestamp with time zone not null default now(),
    writed_at timestamp with time zone null,
    constraint roles_pkey primary key (id),
    constraint roles_name_key unique (name)
);

