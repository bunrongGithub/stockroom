create table if not exists public.user_role (
    id         bigint generated by default as identity not null,
    user_id    uuid   not null references auth.users (id) on delete cascade,
    role_id    bigint not null references public.roles (id) on delete cascade,
    company_id bigint not null references public.company (id) on delete cascade,
    created_at timestamp with time zone not null default now(),
    writed_at timestamp with time zone null,
    constraint user_role_pkey primary key (id),
    constraint user_role_user_id_role_id_company_id_key unique (user_id, role_id, company_id)
);
create index if not exists user_role_user_id_idx on public.user_role (user_id);
create index if not exists user_role_role_id_idx on public.user_role (role_id);
create index if not exists user_role_company_id_idx on public.user_role (company_id);


create table if not exists public.modules (
    id         bigint generated by default as identity not null,
    key       text   not null,
    label     text   not null,
    path      text   not null,
    component text   not null,
    parent_id bigint null references public.modules (id) on delete cascade,
    icon     text   null,
    sort_order integer not null default 0,
    is_active boolean not null default true,
    created_at timestamp with time zone not null default now(),
    writed_at timestamp with time zone null,
    constraint modules_pkey primary key (id),
    constraint modules_key_key unique (key)
);


create table if not exists public.role_module_permission (
    id bigint generated by default as identity not null,
    role_id bigint not null references public.roles (id) on delete cascade,
    module_id bigint not null references public.modules (id) on delete cascade,
    can_view boolean not null default false,
    can_create boolean not null default false,
    can_update boolean not null default false,
    can_delete boolean not null default false,
    can_export boolean not null default false,
    created_at timestamp with time zone not null default now(),
    writed_at timestamp with time zone null,
    constraint role_module_permission_pkey primary key (id),
    constraint role_module_permission_role_id_module_id_key unique (role_id, module_id)
);
